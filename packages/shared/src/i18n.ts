export const dictionaries = { en, es, fr, pt, de, hi, ar } as const;
export type LocaleCode = keyof typeof dictionaries;

export function isRtl(locale: string): boolean {
  return locale.toLowerCase().startsWith('ar') || locale.toLowerCase().startsWith('he') || locale.toLowerCase().startsWith('fa');
}

export function translate(locale: string, key: MessageKey, vars?: Record<string, string | number>): string {
  const code = (locale.toLowerCase().split('-')[0] ?? 'en') as LocaleCode;
  const table = dictionaries[code] ?? dictionaries.en;
  let value: string = table[key] ?? dictionaries.en[key];
  if (vars) {
    for (const [name, replacement] of Object.entries(vars)) {
      value = value.replaceAll(`{${name}}`, String(replacement));
    }
  }
  return value;
}
